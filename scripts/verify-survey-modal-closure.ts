import { studentSurveyService } from '../src/services/StudentSurveyService';
import { surveySyncService } from '../src/services/SurveySyncService';
import { surveyTemplateService } from '../src/services/SurveyTemplateService';
import { studentService } from '../src/services/StudentService';
import { authService } from '../src/services/AuthService';
import { tenantService } from '../src/services/TenantService';
import { StudentSurveyResponse } from '../src/types';

async function runTests() {
  console.log('================================================================');
  console.log('--- BẮT ĐẦU KIỂM THỬ TÍNH NĂNG ĐÓNG / MỞ PHIẾU KHẢO SÁT GVCN ---');
  console.log('================================================================\n');
  let passCount = 0;
  let failCount = 0;

  const recordResult = (id: number, name: string, passed: boolean, note: string) => {
    if (passed) {
      passCount++;
      console.log(`[PASS] Phép thử ${id}: ${name} \n  -> ${note}`);
    } else {
      failCount++;
      console.error(`[FAIL] Phép thử ${id}: ${name} \n  -> ${note}`);
    }
  };

  try {
    authService.switchRole('TEACHER');
    const currentTenantId = tenantService.getActiveTenantId();
    const students = studentService.getAll();
    if (students.length === 0) throw new Error('Không tìm thấy danh sách học sinh');
    const studentA = students[0];
    const studentB = students[1] || students[0];

    const surveyA: StudentSurveyResponse = {
      id: 'test-survey-a-001',
      tenantId: currentTenantId,
      classId: 'class-12a1',
      source: 'APP',
      studentId: studentA.id,
      surveyType: 'BEGINNING_OF_YEAR',
      surveyTemplateId: 'template-grade12-default-v1',
      status: 'SUBMITTED',
      version: 1,
      schoolYear: '2025 - 2026',
      submittedAt: new Date().toISOString(),
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      answers: {
        conductSelfAssessment: {
          rating: 'Tốt',
          evidence: 'Hoàn thành tốt các phong trào thi đua'
        },
        contact: {
          phone: '0912345678'
        }
      }
    };

    const surveyB: StudentSurveyResponse = {
      id: 'test-survey-b-002',
      tenantId: currentTenantId,
      classId: 'class-12a1',
      source: 'APP',
      studentId: studentB.id,
      surveyType: 'BEGINNING_OF_YEAR',
      surveyTemplateId: 'template-grade12-default-v1',
      status: 'SUBMITTED',
      version: 1,
      schoolYear: '2025 - 2026',
      submittedAt: new Date().toISOString(),
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      answers: {
        conductSelfAssessment: {
          rating: 'Khá',
          evidence: 'Đi học đúng giờ'
        },
        contact: {
          phone: '0987654321'
        }
      }
    };

    // Đưa vào service cache
    (studentSurveyService as any).surveys = [surveyA, surveyB];

    // Mô phỏng state machine của TeacherSurveyManagementView
    let selectedSurveyForDetail: StudentSurveyResponse | null = null;
    let isDetailModalOpen: boolean = Boolean(false);
    let handledHighlightIdRef = { current: null as string | null };

    const handleOpenDetailModal = (survey: StudentSurveyResponse) => {
      selectedSurveyForDetail = survey;
      isDetailModalOpen = true;
    };

    const handleCloseDetailModal = () => {
      isDetailModalOpen = false;
      selectedSurveyForDetail = null;
    };

    // Phép thử 1: Nhấn "Xem" -> phiếu mở đúng
    handleOpenDetailModal(surveyA);
    const test1Passed = Boolean(isDetailModalOpen) && selectedSurveyForDetail?.id === surveyA.id && selectedSurveyForDetail?.studentId === studentA.id;
    recordResult(1, 'Nhấn "Xem" → phiếu mở đúng', test1Passed, `Đã mở đúng phiếu ID=${surveyA.id} của học sinh ${studentA.fullName}`);

    // Phép thử 2: Đóng phiếu -> phiếu biến mất
    handleCloseDetailModal();
    const test2Passed = !isDetailModalOpen && selectedSurveyForDetail === null;
    recordResult(2, 'Đóng phiếu → phiếu biến mất', test2Passed, 'isDetailModalOpen=false, selectedSurveyForDetail=null, phiếu hoàn toàn ẩn khỏi giao diện');

    // Tạo proposal để test
    const proposal: any = {
      id: 'prop-test-001',
      tenantId: currentTenantId,
      surveyId: surveyA.id,
      studentId: studentA.id,
      studentName: studentA.fullName,
      studentCode: studentA.code || 'HS01',
      category: 'CONDUCT_SELF_EVALUATION',
      title: 'Tự đánh giá Rèn luyện HKI',
      sourceField: 'conductSelfAssessment',
      currentValue: 'Chưa đánh giá',
      proposedValue: {
        selfAssessment: 'Tốt',
        conductNote: 'Gương mẫu trong lớp'
      },
      status: 'PENDING',
      isAutoGenerated: true,
      templateId: surveyA.surveyTemplateId,
      createdAt: new Date().toISOString()
    };
    (surveySyncService as any).proposals.push(proposal);

    // Hàm mô phỏng refreshData và subscriber trong TeacherSurveyManagementView
    const simulateDataRefresh = () => {
      // Khi dữ liệu được tải lại hoặc update từ service:
      // highlightSurveyId cũ nếu có trong props KHÔNG ĐƯỢC mở lại vì handledHighlightIdRef.current === highlightSurveyId
      const currentHighlightProp = surveyA.id;
      if (currentHighlightProp && currentHighlightProp !== handledHighlightIdRef.current) {
        // Chỉ mở nếu là ID mới chưa từng xử lý
        handledHighlightIdRef.current = currentHighlightProp;
        selectedSurveyForDetail = surveyA;
        isDetailModalOpen = true;
      }
      // Dữ liệu nội bộ cập nhật:
      const surveys = studentSurveyService.getAll();
      const proposals = surveySyncService.getProposals();
    };

    // Đánh dấu highlightSurveyId của surveyA đã được xử lý (khi người dùng đã mở và đóng)
    handledHighlightIdRef.current = surveyA.id;

    // Phép thử 3: Đóng phiếu rồi nhấn "Duyệt" -> phiếu không tự mở lại
    await surveySyncService.approveProposal(proposal.id, 'GVCN duyệt đề xuất');
    simulateDataRefresh();
    const test3Passed = isDetailModalOpen === false && selectedSurveyForDetail === null;
    recordResult(3, 'Đóng phiếu rồi nhấn "Duyệt" → phiếu không tự mở lại', test3Passed, 'Sau khi duyệt proposal và dữ liệu đồng bộ, phiếu vẫn ở trạng thái đóng');

    // Phép thử 4: Đóng phiếu rồi nhấn "Từ chối" -> phiếu không tự mở lại
    const proposalReject: any = {
      id: 'prop-test-002',
      tenantId: currentTenantId,
      surveyId: surveyA.id,
      studentId: studentA.id,
      studentName: studentA.fullName,
      studentCode: studentA.code || 'HS01',
      category: 'CONTACT_UPDATE',
      title: 'Cập nhật địa chỉ liên hệ',
      sourceField: 'contact',
      currentValue: 'Hà Nội',
      proposedValue: 'TP.HCM',
      status: 'PENDING',
      isAutoGenerated: true,
      templateId: surveyA.surveyTemplateId,
      createdAt: new Date().toISOString()
    };
    (surveySyncService as any).proposals.push(proposalReject);
    await surveySyncService.rejectProposal(proposalReject.id, 'Thông tin không chính xác');
    simulateDataRefresh();
    const test4Passed = isDetailModalOpen === false && selectedSurveyForDetail === null;
    recordResult(4, 'Đóng phiếu rồi nhấn "Từ chối" → phiếu không tự mở lại', test4Passed, 'Sau khi từ chối đề xuất, phiếu vẫn tiếp tục đóng');

    // Phép thử 5: Đóng phiếu rồi nhấn "Đồng bộ" -> phiếu không tự mở lại
    await surveySyncService.processSurvey(surveyA.id, { force: true });
    simulateDataRefresh();
    const test5Passed = isDetailModalOpen === false && selectedSurveyForDetail === null;
    recordResult(5, 'Đóng phiếu rồi nhấn "Đồng bộ" → phiếu không tự mở lại', test5Passed, 'Sau khi đồng bộ toàn bộ phản hồi, phiếu vẫn tiếp tục đóng');

    // Phép thử 6: Đóng phiếu rồi tải lại danh sách -> phiếu vẫn đóng
    simulateDataRefresh();
    const test6Passed = isDetailModalOpen === false && selectedSurveyForDetail === null;
    recordResult(6, 'Đóng phiếu rồi tải lại danh sách → phiếu vẫn đóng', test6Passed, 'Khi tải lại danh sách (refreshData), phiếu giữ nguyên trạng thái đóng');

    // Phép thử 7: Thao tác thất bại -> phiếu không tự mở lại
    try {
      await surveySyncService.approveProposal('NON_EXISTENT_ID_999', 'Note');
    } catch (err: any) {
      // Bắt lỗi thao tác thất bại
    }
    const test7Passed = isDetailModalOpen === false && selectedSurveyForDetail === null;
    recordResult(7, 'Thao tác thất bại → phiếu không tự mở lại', test7Passed, 'Thao tác nghiệp vụ thất bại được xử lý an toàn, không kích hoạt mở phiếu');

    // Phép thử 8: Nhấn "Xem" lần nữa → mở lại đúng phiếu
    handleOpenDetailModal(surveyA);
    const test8Passed = Boolean(isDetailModalOpen) && selectedSurveyForDetail?.id === surveyA.id;
    recordResult(8, 'Nhấn "Xem" lần nữa → mở lại đúng phiếu', test8Passed, `GVCN chủ động mở lại phiếu ID=${surveyA.id} thành công`);

    // Phép thử 9: Chuyển giữa các phiếu → nội dung hiển thị đúng học viên và bài khảo sát
    handleOpenDetailModal(surveyB);
    const test9Passed = Boolean(isDetailModalOpen) && 
      selectedSurveyForDetail?.id === surveyB.id && 
      selectedSurveyForDetail?.studentId === studentB.id &&
      (selectedSurveyForDetail?.answers as any)?.conductSelfAssessment?.rating === 'Khá';
    recordResult(9, 'Chuyển giữa các phiếu → nội dung hiển thị đúng học viên và bài khảo sát', test9Passed, `Chuyển sang phiếu ID=${surveyB.id} của học sinh ${studentB.fullName} với nội dung tự xếp loại Khá chính xác, không nhầm dữ liệu`);

    // Đóng phiếu sau khi xem
    handleCloseDetailModal();

    // Phép thử 10: Kiểm tra các chức năng khảo sát liên quan vẫn hoạt động bình thường
    const allProposals = surveySyncService.getProposals();
    const approvedCheck = allProposals.find(p => p.id === proposal.id);
    const rejectedCheck = allProposals.find(p => p.id === proposalReject.id);
    const templates = surveyTemplateService.getTemplatesBySchoolYear('2025 - 2026');
    const test10Passed = approvedCheck?.status === 'APPROVED' && rejectedCheck?.status === 'REJECTED' && templates.length > 0;
    recordResult(10, 'Kiểm tra các chức năng khảo sát liên quan vẫn hoạt động bình thường', test10Passed, 'Duyệt đề xuất, từ chối đề xuất, hệ thống template và sync audit hoạt động ổn định và chính xác 100%');

    console.log(`\n================================================================`);
    console.log(`TỔNG KẾT: ${passCount}/10 BÀI TEST PASS, ${failCount} FAIL`);
    console.log(`================================================================`);
    if (failCount > 0) {
      process.exit(1);
    }
  } catch (error: any) {
    console.error('Lỗi khi chạy kiểm thử:', error);
    process.exit(1);
  }
}

runTests();
